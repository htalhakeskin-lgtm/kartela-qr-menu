import { SW_IMAGE_CACHE_LIMIT } from "../../config/limits";
import { SW_IMAGE_HOSTS, SW_STORED_AT_HEADER, SW_WARM_MESSAGE } from "./sw-protocol";

/**
 * A venue's service worker (ADR-0005 §7, REQ-017, D-13), hand-written, no library. Served as
 * /sw.js on the venue's own domain, scope "/", so it never sees another venue or the platform.
 *
 * - Pages (documents and RSC payloads): network first, past the HTTP cache (its stale copy would
 *   hide a change such as the view cookie's Keşfet); after 3 s without an answer, or offline,
 *   the cached copy — stamped with the time it was stored, which the offline note shows. A page
 *   never opened falls back to the venue's /cevrimdisi page in the same language.
 * - /_next/static: cache first (hashed file names never change).
 * - Stock photos on the image CDNs: cache first, fetched with CORS (opaque responses would count
 *   megabytes against the storage quota each), at most SW_IMAGE_CACHE_LIMIT per venue (P-05).
 * - /api, the panel and the worker itself pass through untouched.
 *
 * The first visit loads before the worker exists; the page then sends a "warm" message with its
 * address and the files it loaded, and the worker stores them. A new deploy changes `version`,
 * the cache names with it, and the old caches are deleted on activation.
 */

const NETWORK_TIMEOUT_MS = 3000;

export type ServiceWorkerOptions = {
  slug: string;
  /** Changes with every deploy (commit) so a new worker replaces the caches. */
  version: string;
  /** "/cevrimdisi" for the default language, "/en/cevrimdisi" … for the others. */
  offlinePages: Record<string, string>;
  defaultLocale: string;
};

/** Cache names: the venue's slug first, so a worker only ever deletes its own venue's caches. */
export function swCacheNames(slug: string, version: string) {
  const prefix = `kartela-${slug}-`;
  return {
    prefix,
    pages: `${prefix}sayfa-${version}`,
    assets: `${prefix}dosya-${version}`,
    images: `${prefix}gorsel`,
  };
}

export function venueServiceWorker(options: ServiceWorkerOptions): string {
  const names = swCacheNames(options.slug, options.version);
  const config = {
    names,
    offlinePages: options.offlinePages,
    defaultLocale: options.defaultLocale,
    imageHosts: SW_IMAGE_HOSTS,
    imageLimit: SW_IMAGE_CACHE_LIMIT,
    timeout: NETWORK_TIMEOUT_MS,
    warm: SW_WARM_MESSAGE,
    storedAt: SW_STORED_AT_HEADER,
  };
  return `"use strict";
// Kartela — ${options.slug} service worker (ADR-0005 §7). Generated by src/platform/routes/venue-sw.ts.
const C = ${JSON.stringify(config)};
const KEEP = [C.names.pages, C.names.assets, C.names.images];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(C.names.pages)
      .then((cache) => Promise.all(Object.values(C.offlinePages).map((path) => storePage(cache, path))))
      .catch(() => undefined),
  );
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      for (const name of await caches.keys()) {
        if (name.startsWith(C.names.prefix) && !KEEP.includes(name)) await caches.delete(name);
      }
      await self.clients.claim();
    })(),
  );
});

self.addEventListener("message", (event) => {
  const data = event.data;
  if (!data || data.type !== C.warm || !Array.isArray(data.urls)) return;
  event.waitUntil(warm(data.urls));
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin === self.location.origin) {
    const path = url.pathname;
    if (path.startsWith("/api/") || path.startsWith("/panel") || path === "/sw.js") return;
    if (path.startsWith("/_next/static/")) {
      event.respondWith(cacheFirst(C.names.assets, request));
      return;
    }
    if (request.mode === "navigate" || request.headers.get("rsc") === "1") {
      event.respondWith(networkFirst(request, url));
    }
    return;
  }
  if (request.destination === "image" && C.imageHosts.includes(url.hostname)) {
    event.respondWith(cachedImage(request.url));
  }
});

async function stamped(response) {
  const headers = new Headers(response.headers);
  headers.set(C.storedAt, new Date().toISOString());
  return new Response(await response.blob(), {
    status: response.status,
    statusText: response.statusText,
    headers,
  });
}

// Pages are always asked from the server: the HTTP cache may hold a stale copy that
// stale-while-revalidate would hand to the worker's fetch (navigations ignore it, fetch() does not).
function fromServer(request) {
  if (request.mode === "navigate") {
    return new Request(request.url, {
      credentials: "include",
      cache: "no-cache",
      redirect: "manual",
      headers: { Accept: request.headers.get("accept") || "text/html" },
    });
  }
  return new Request(request, { cache: "no-cache" });
}

async function storePage(cache, path) {
  const response = await fetch(path, { credentials: "same-origin", cache: "no-cache" });
  if (response.ok) await cache.put(path, await stamped(response));
}

async function cacheFirst(name, request) {
  const cache = await caches.open(name);
  const hit = await cache.match(request);
  if (hit) return hit;
  const response = await fetch(request);
  if (response.ok) await cache.put(request, response.clone());
  return response;
}

function offlinePageFor(path) {
  const first = path.split("/")[1] || "";
  return C.offlinePages[first] || C.offlinePages[C.defaultLocale];
}

async function networkFirst(request, url) {
  const cache = await caches.open(C.names.pages);
  const network = fetch(fromServer(request)).then(async (response) => {
    if (response.ok && response.type === "basic") await cache.put(request, await stamped(response.clone()));
    return response;
  });
  network.catch(() => undefined);
  try {
    return await new Promise((resolve, reject) => {
      const timer = setTimeout(() => reject(new Error("timeout")), C.timeout);
      network.then(
        (response) => {
          clearTimeout(timer);
          resolve(response);
        },
        (error) => {
          clearTimeout(timer);
          reject(error);
        },
      );
    });
  } catch {
    const hit =
      (await cache.match(request, { ignoreVary: true })) ||
      (await cache.match(url.origin + url.pathname, { ignoreVary: true, ignoreSearch: true }));
    if (hit) return hit;
    if (request.mode === "navigate") {
      const offline = await cache.match(offlinePageFor(url.pathname), { ignoreVary: true });
      if (offline) return offline;
    }
    return network;
  }
}

async function cachedImage(href) {
  const cache = await caches.open(C.names.images);
  const hit = await cache.match(href);
  if (hit) return hit;
  try {
    const response = await fetch(href, { mode: "cors", credentials: "omit" });
    if (response.ok) {
      await cache.put(href, response.clone());
      const keys = await cache.keys();
      for (const key of keys.slice(0, Math.max(0, keys.length - C.imageLimit))) await cache.delete(key);
    }
    return response;
  } catch {
    return fetch(href, { mode: "no-cors" });
  }
}

async function warm(urls) {
  for (const raw of urls) {
    try {
      const url = new URL(raw, self.location.origin);
      if (url.origin === self.location.origin) {
        if (url.pathname.startsWith("/_next/static/")) {
          const cache = await caches.open(C.names.assets);
          if (!(await cache.match(url.href))) {
            const response = await fetch(url.href);
            if (response.ok) await cache.put(url.href, response);
          }
        } else if (!url.pathname.startsWith("/api/")) {
          await storePage(await caches.open(C.names.pages), url.pathname + url.search);
        }
      } else if (C.imageHosts.includes(url.hostname)) {
        await cachedImage(url.href);
      }
    } catch {
      // One file failing must not stop the others; the next visit tries again.
    }
  }
}
`;
}
